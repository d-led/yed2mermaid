# Generates the Homebrew formula for yed2mermaid from release checksums.
#
# Expects the following environment variables:
#   VERSION           e.g. 1.2.3
#   SHA_MACOS_ARM64   sha256 of yed2mermaid-<version>-macos-arm64.tar.gz
#   SHA_MACOS_X64     sha256 of yed2mermaid-<version>-macos-x64.tar.gz
#   SHA_LINUX_ARM64   sha256 of yed2mermaid-<version>-linux-arm64.tar.gz
#   SHA_LINUX_X64     sha256 of yed2mermaid-<version>-linux-x64.tar.gz
#
# Usage:
#   VERSION=1.2.3 SHA_MACOS_ARM64=... SHA_MACOS_X64=... \
#   SHA_LINUX_ARM64=... SHA_LINUX_X64=... \
#   scripts/generate-homebrew-formula.sh > yed2mermaid.rb
set -euo pipefail

version="${VERSION:?VERSION is required}"
sha_macos_arm64="${SHA_MACOS_ARM64:?SHA_MACOS_ARM64 is required}"
sha_macos_x64="${SHA_MACOS_X64:?SHA_MACOS_X64 is required}"
sha_linux_arm64="${SHA_LINUX_ARM64:?SHA_LINUX_ARM64 is required}"
sha_linux_x64="${SHA_LINUX_X64:?SHA_LINUX_X64 is required}"

base="https://github.com/d-led/yed2mermaid/releases/download/v${version}"

cat <<EOF
# typed: false
# frozen_string_literal: true

# This file was generated by d-led/yed2mermaid (scripts/generate-homebrew-formula.sh).
# Do not edit by hand; update via the release workflow or re-run the generator.
class Yed2mermaid < Formula
  desc "Convert yEd GraphML flowcharts to Mermaid"
  homepage "https://github.com/d-led/yed2mermaid"
  version "${version}"
  license "MPL-2.0"

  on_macos do
    if Hardware::CPU.arm?
      url "${base}/yed2mermaid-${version}-macos-arm64.tar.gz"
      sha256 "${sha_macos_arm64}"
    else
      url "${base}/yed2mermaid-${version}-macos-x64.tar.gz"
      sha256 "${sha_macos_x64}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "${base}/yed2mermaid-${version}-linux-arm64.tar.gz"
      sha256 "${sha_linux_arm64}"
    else
      url "${base}/yed2mermaid-${version}-linux-x64.tar.gz"
      sha256 "${sha_linux_x64}"
    end
  end

  def install
    bin.install "yed2mermaid"
  end

  test do
    assert_match "yed2mermaid", shell_output("#{bin}/yed2mermaid --version")
  end
end
EOF
